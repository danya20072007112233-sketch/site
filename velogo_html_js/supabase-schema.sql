create table if not exists public.scooters (
  id bigint generated by default as identity primary key,
  code text unique not null,
  lat double precision not null,
  lng double precision not null,
  battery integer not null default 100 check (battery between 0 and 100),
  status text not null default 'available' check (status in ('available','busy'))
);
create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  scooter_code text not null references public.scooters(code),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create table if not exists public.rides (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  scooter_code text not null references public.scooters(code),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  duration_minutes integer,
  cost integer
);
alter table public.scooters enable row level security;
alter table public.reservations enable row level security;
alter table public.rides enable row level security;
drop policy if exists "Scooters readable by everyone" on public.scooters;
create policy "Scooters readable by everyone" on public.scooters for select using (true);
drop policy if exists "Users read own reservations" on public.reservations;
create policy "Users read own reservations" on public.reservations for select to authenticated using (auth.uid()=user_id);
drop policy if exists "Users create own reservations" on public.reservations;
create policy "Users create own reservations" on public.reservations for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Users read own rides" on public.rides;
create policy "Users read own rides" on public.rides for select to authenticated using (auth.uid()=user_id);
drop policy if exists "Users create own rides" on public.rides;
create policy "Users create own rides" on public.rides for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Users update own rides" on public.rides;
create policy "Users update own rides" on public.rides for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
